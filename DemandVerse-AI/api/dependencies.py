import os
import pandas as pd
from functools import lru_cache
from typing import Optional

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
OUTPUTS_DIR = os.path.join(BASE_DIR, 'demandverse_ai_outputs')
CUSTOM_OUTPUTS_DIR = os.path.join(BASE_DIR, 'outputs')

@lru_cache()
def get_clean_sales() -> pd.DataFrame:
    path = os.path.join(OUTPUTS_DIR, 'data', 'clean_sales.csv')
    return pd.read_csv(path)

@lru_cache()
def get_final_forecasts() -> pd.DataFrame:
    path = os.path.join(OUTPUTS_DIR, 'forecasts', 'final_forecasts.csv')
    return pd.read_csv(path)

@lru_cache()
def get_model_comparison() -> pd.DataFrame:
    path = os.path.join(OUTPUTS_DIR, 'forecasts', 'model_comparison.csv')
    return pd.read_csv(path)

@lru_cache()
def get_inventory_recommendations() -> pd.DataFrame:
    path = os.path.join(OUTPUTS_DIR, 'inventory', 'inventory_recommendations.csv')
    return pd.read_csv(path)

@lru_cache()
def get_what_if_analysis() -> pd.DataFrame:
    path = os.path.join(OUTPUTS_DIR, 'financial', 'what_if_analysis.csv')
    if not os.path.exists(path):
        # Fallback to local outputs if generated by ML Pipeline Phase C
        path = os.path.join(CUSTOM_OUTPUTS_DIR, 'what_if_analysis.csv')
    return pd.read_csv(path)

@lru_cache()
def get_financial_impact() -> pd.DataFrame:
    path = os.path.join(CUSTOM_OUTPUTS_DIR, 'financial_impact.csv')
    if not os.path.exists(path):
        # Fallback to Colab outputs
        path = os.path.join(OUTPUTS_DIR, 'financial', 'financial_impact.csv')
    return pd.read_csv(path)

